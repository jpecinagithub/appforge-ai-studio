/**
 * Project lifecycle: create (scaffold from template + git init + initial
 * PROJECT_CONTEXT.md), delete, and safe path helpers.
 */

import { execFileSync } from 'node:child_process';
import { randomUUID } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import type Database from 'better-sqlite3';
import type { FileNode, Project } from 'appforge-shared';

export const nowIso = () => new Date().toISOString();

export function projectDir(dataDir: string, id: string): string {
  return path.join(dataDir, 'projects', id);
}

export function frontendDir(dataDir: string, id: string): string {
  return path.join(projectDir(dataDir, id), 'frontend');
}

/**
 * Resolve `p` inside `root`; throws {code:'INVALID_PATH'} on traversal,
 * absolute paths or null bytes.
 */
export function resolveIn(root: string, p: string): string {
  if (typeof p !== 'string' || p.length === 0 || p.includes('\0')) {
    const e = new Error(`invalid path: ${JSON.stringify(p)}`) as Error & { code: string };
    e.code = 'INVALID_PATH';
    throw e;
  }
  const resolved = path.resolve(root, p);
  if (resolved !== root && !resolved.startsWith(root + path.sep)) {
    const e = new Error(`path escapes project directory: ${p}`) as Error & { code: string };
    e.code = 'INVALID_PATH';
    throw e;
  }
  return resolved;
}

export function rowToProject(r: Record<string, any>): Project {
  return {
    id: r.id,
    name: r.name,
    description: r.description ?? '',
    type: r.type === 'dynamic' ? 'dynamic' : 'static',
    status: r.status ?? 'active',
    model: r.model ?? null,
    createdAt: r.created_at,
    updatedAt: r.updated_at,
    previewUrl: r.preview_url ?? null,
    thumbnailUrl: r.preview_url
      ? `/p/${encodeURIComponent(r.id)}/__appforge/thumbnail.webp?v=${encodeURIComponent(r.updated_at ?? '')}`
      : null,
    productionUrl: r.production_url ?? null,
    config: r.config_json ? JSON.parse(r.config_json) : {},
  };
}

function initGit(dir: string): void {
  try {
    execFileSync('git', ['init', '-q'], { cwd: dir, stdio: 'ignore' });
    execFileSync('git', ['add', '-A'], { cwd: dir, stdio: 'ignore' });
    execFileSync('git', ['-c', 'user.name=AppForge', '-c', 'user.email=appforge@local', 'commit', '-q', '-m', 'initial commit'], {
      cwd: dir,
      stdio: 'ignore',
    });
  } catch (e) {
    console.warn('[projects] git init failed (revisions will be unavailable):', (e as Error).message);
  }
}

function initialContext(name: string, description: string): string {
  return [
    `# PROJECT_CONTEXT.md — ${name} (internal, auto-generated by the agent)`,
    '',
    `- Created: ${nowIso()}`,
    `- Description: ${description || '(none)'}`,
    '- Stack: Vite + React + TypeScript + plain CSS (static template)',
    '',
    '## Structure (project root)',
    'dir: frontend/   — the Vite+React app (this is what the agent edits)',
    'dir: metadata/   — reserved for project metadata',
    'dir: logs/       — reserved for logs',
    'file: PROJECT_CONTEXT.md — this file',
    '',
    '## Recent changes',
    '(none yet — initial scaffold from templates/static-react/)',
    '',
    '## Last run summary',
    '(no runs yet)',
    '',
    '## Known errors',
    '(none)',
    '',
  ].join('\n');
}

export interface CreateProjectInput {
  name: string;
  description?: string;
  type?: 'static' | 'dynamic';
}

/**
 * Fase 1: only the static template is scaffolded. A requested type of
 * 'dynamic' is stored as-is but still uses the static template until the
 * Fase 2 dynamic template/backend flow lands (see README).
 */
export function createProject(db: Database.Database, dataDir: string, templatesDir: string, input: CreateProjectInput): Project {
  const id = randomUUID();
  const dir = projectDir(dataDir, id);
  for (const sub of ['frontend', 'metadata', 'logs']) {
    fs.mkdirSync(path.join(dir, sub), { recursive: true });
  }
  const template = path.join(templatesDir, 'static-react');
  if (!fs.existsSync(path.join(template, 'package.json'))) {
    throw new Error(`template not found: ${template}`);
  }
  fs.cpSync(template, path.join(dir, 'frontend'), {
    recursive: true,
    filter: (src) => !src.split(path.sep).includes('node_modules'),
  });
  initGit(dir);
  fs.writeFileSync(path.join(dir, 'PROJECT_CONTEXT.md'), initialContext(input.name, input.description ?? ''), 'utf8');

  const created = nowIso();
  db.prepare(
    'INSERT INTO projects(id,name,description,type,status,model,created_at,updated_at,preview_url,production_url,config_json) VALUES (?,?,?,?,?,?,?,?,?,?,?)',
  ).run(id, input.name, input.description ?? '', input.type ?? 'static', 'active', null, created, created, null, null, '{}');
  return getProject(db, id)!;
}

export function getProject(db: Database.Database, id: string): Project | null {
  const row = db.prepare('SELECT * FROM projects WHERE id=?').get(id) as Record<string, any> | undefined;
  return row ? rowToProject(row) : null;
}

export function deleteProject(db: Database.Database, dataDir: string, id: string): boolean {
  const existing = getProject(db, id);
  if (!existing) return false;
  fs.rmSync(projectDir(dataDir, id), { recursive: true, force: true });
  const runIds = (db.prepare('SELECT id FROM runs WHERE project_id=?').all(id) as Array<{ id: string }>).map((r) => r.id);
  const delEvents = db.prepare('DELETE FROM run_events WHERE run_id=?');
  for (const rid of runIds) delEvents.run(rid);
  db.prepare('DELETE FROM runs WHERE project_id=?').run(id);
  db.prepare('DELETE FROM messages WHERE project_id=?').run(id);
  db.prepare('DELETE FROM builds WHERE project_id=?').run(id);
  db.prepare('DELETE FROM revisions WHERE project_id=?').run(id);
  db.prepare('DELETE FROM deployments WHERE project_id=?').run(id);
  db.prepare('DELETE FROM projects WHERE id=?').run(id);
  return true;
}

/** FileNode tree of frontend/ (used by GET /files). */
export function buildFileTree(frontend: string): FileNode[] {
  const ignored = new Set(['node_modules', 'dist', '.git']);
  const walk = (dir: string, rel: string): FileNode[] => {
    const nodes: FileNode[] = [];
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      if (e.isDirectory() && ignored.has(e.name)) continue;
      const childRel = rel ? `${rel}/${e.name}` : e.name;
      if (e.isDirectory()) nodes.push({ name: e.name, path: childRel, type: 'dir', children: walk(path.join(dir, e.name), childRel) });
      else if (e.isFile()) nodes.push({ name: e.name, path: childRel, type: 'file' });
    }
    nodes.sort((a, b) => (a.type === b.type ? a.name.localeCompare(b.name) : a.type === 'dir' ? -1 : 1));
    return nodes;
  };
  return walk(frontend, '');
}

/** Recursive byte size of a directory (0 when missing). */
export function dirSize(dir: string): number {
  let total = 0;
  const walk = (d: string) => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const abs = path.join(d, e.name);
      if (e.isDirectory()) walk(abs);
      else if (e.isFile()) {
        try {
          total += fs.statSync(abs).size;
        } catch {
          /* ignore */
        }
      }
    }
  };
  try {
    walk(dir);
  } catch {
    /* missing */
  }
  return total;
}
